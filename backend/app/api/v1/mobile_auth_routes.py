@router.post("/login/doctor", response_model=MobileAuthResponse)
def login_doctor(payload: DoctorLoginRequest, db: Session = Depends(get_session)):
    """
    Doctor logs in using email, contact number, or doctor ID + password.
    Credentials are generated by Hospital Management Admin — no self-registration.
    """
    identifier = payload.identifier.strip()
    ident_lower = identifier.lower()

    # Match by email (case-insensitive), contact_number, or doctor ID (case-insensitive)
    all_doctors = db.exec(select(Doctor)).all()
    doctor = None
    for d in all_doctors:
        if (d.email and d.email.lower() == ident_lower) or \
           (d.contact_number and d.contact_number.strip() == identifier) or \
           (d.id and d.id.lower() == ident_lower):
            doctor = d
            break

    if not doctor:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail=f"No doctor account found matching '{identifier}'. Check your email/phone or register doctor in Hospital Admin."
        )

    if not doctor.password_hash:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Doctor account has no password set. Contact your hospital admin to reset credentials."
        )

    if not verify_password(payload.password, doctor.password_hash):
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Incorrect password. Please try again or contact your hospital admin."
        )

    if not doctor.is_active:
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="Your doctor account is currently deactivated. Contact hospital admin."
        )

    # Resolve hospital name
    hospital = db.exec(select(Hospital).where(Hospital.id == doctor.hospital_id)).first()
    hospital_name = hospital.name if hospital else "Unknown Hospital"

    # Generate JWT
    token = create_access_token(data={
        "sub": doctor.id,
        "role": "doctor",
        "hospital_id": doctor.hospital_id
    })

    return MobileAuthResponse(
        success=True,
        token=token,
        role="doctor",
        user_id=doctor.id,
        user_name=doctor.name,
        hospital_id=doctor.hospital_id,
        hospital_name=hospital_name,
        specialization=doctor.specialization,
        contact_number=doctor.contact_number,
        email=doctor.email,
        shift_timing=doctor.shift_timing
    )


